--

CREATE FUNCTION public.cash_check_in(p_check_id uuid) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
DECLARE
    v_check record;
    v_cash_management_settings jsonb;
    v_current_cash_balance numeric;
    v_new_cash_balance numeric;
BEGIN
    -- Get the check details
    SELECT * INTO v_check FROM checks_in WHERE id = p_check_id;

    IF v_check IS NULL THEN
        RAISE EXCEPTION 'Check not found';
    END IF;

    IF v_check.status = 'cashed' THEN
        RAISE EXCEPTION 'Check has already been cashed';
    END IF;

    -- Update the check status
    UPDATE checks_in SET status = 'cashed' WHERE id = p_check_id;

    -- Get current cash balance
    SELECT value INTO v_cash_management_settings FROM system_settings WHERE key = 'cash_management';
    v_current_cash_balance := (v_cash_management_settings->>'current_balance')::numeric;

    -- Calculate new balance
    v_new_cash_balance := v_current_cash_balance + v_check.amount;

    -- Update cash management settings
    UPDATE system_settings 
    SET value = jsonb_set(value, '{current_balance}', to_jsonb(v_new_cash_balance))
    WHERE key = 'cash_management';

    -- Log the cash transaction
    INSERT INTO cash_on_hand (amount, type, memo)
    VALUES (v_check.amount, 'in', 'Cashed incoming check #' || COALESCE(v_check.check_number, 'N/A'));

END;
$$;


