CREATE FUNCTION public.calculate_fee_v2(p_account_number text, p_debit_cash_entries jsonb, p_debit_checks jsonb, p_credit_checks jsonb) RETURNS TABLE(fee numeric, memo text)
    LANGUAGE plpgsql SECURITY DEFINER
    AS $_$
    DECLARE
        fee_settings jsonb;
        total_fee numeric := 0;
        fee_memo text := '';
        regular_fee numeric := 0;
        rush_fee numeric := 0;
        regular_memo text[] := ARRAY[]::text[];
        rush_memo text[] := ARRAY[]::text[];
        
        cash_debit_config jsonb;
        waiver_config jsonb;
        charge_fee boolean;
        start_date date;
        total_past_debit numeric;
        cash_entry record;
        total_non_rush_cash_debit numeric := 0;
        total_rush_cash_debit numeric := 0;

        check_debit_config jsonb;
        debit_check_count integer;
        tier record;
        checks_in_tier integer;
        tier_fee numeric;
        
        credit_check_config jsonb;
        credit_check_count integer;

        rush_config jsonb;
        rush_checks_count integer;
        total_rush_check_amount numeric;

        is_cash_rush boolean := false;
        is_check_rush boolean := false;

        cycle_start_date date;

    BEGIN
        SELECT value INTO fee_settings FROM system_settings WHERE key = 'transaction_fees';
        IF NOT (fee_settings->>'enabled')::boolean THEN
            RETURN QUERY SELECT 0::numeric, ''::text;
            RETURN;
        END IF;

        FOR cash_entry IN SELECT * FROM jsonb_to_recordset(p_debit_cash_entries) AS x(amount numeric, "isRush" boolean) LOOP
            IF cash_entry."isRush" THEN
                total_rush_cash_debit := total_rush_cash_debit + cash_entry.amount;
                is_cash_rush := true;
            ELSE
                total_non_rush_cash_debit := total_non_rush_cash_debit + cash_entry.amount;
            END IF;
        END LOOP;

        cash_debit_config := fee_settings->'cash_debit';
        IF (cash_debit_config->>'enabled')::boolean AND total_non_rush_cash_debit > 0 THEN
            charge_fee := true;
            waiver_config := cash_debit_config->'waiver';
            IF waiver_config->>'mode' = 'never' THEN
                charge_fee := false;
            ELSIF waiver_config->>'mode' = 'conditional' THEN
                start_date := now() - (waiver_config->>'period_days' || ' days')::interval;
                SELECT COALESCE(SUM(t.amount), 0) INTO total_past_debit
                FROM transactions t
                JOIN jsonb_to_recordset(t.fee_details->'debit_cash_entries') as y(amount numeric, "isRush" boolean) ON true
                WHERE t.account_number = p_account_number AND t.type = 'debit' AND t.date >= start_date AND y."isRush" = false;
                IF total_past_debit < (waiver_config->>'threshold_amount')::numeric THEN
                    charge_fee := false;
                END IF;
            END IF;

            IF charge_fee THEN
                IF cash_debit_config->>'fee_type' = 'flat' THEN
                    regular_fee := regular_fee + (cash_debit_config->>'fee_value')::numeric;
                    regular_memo := array_append(regular_memo, 'Cash Debit Fee: $' || (cash_debit_config->>'fee_value')::numeric);
                ELSE 
                    regular_fee := regular_fee + (total_non_rush_cash_debit * (cash_debit_config->>'fee_value')::numeric / 100.0);
                    regular_memo := array_append(regular_memo, 'Cash Debit Fee: ' || (cash_debit_config->>'fee_value')::numeric || '% of $' || total_non_rush_cash_debit);
                END IF;
            END IF;
        END IF;

        check_debit_config := fee_settings->'check_debit';
        debit_check_count := (SELECT COUNT(*) FROM jsonb_to_recordset(p_debit_checks) AS x(amount numeric, "isRush" boolean) WHERE x.amount > 0 AND x."isRush" = false);
        IF (check_debit_config->>'enabled')::boolean AND debit_check_count > 0 THEN
            cycle_start_date := CASE
                WHEN check_debit_config->>'cycle' = 'daily' THEN date_trunc('day', now())
                WHEN check_debit_config->>'cycle' = 'weekly' THEN date_trunc('week', now())
                WHEN check_debit_config->>'cycle' = 'monthly' THEN date_trunc('month', now())
                ELSE '1970-01-01'::date
            END;

            FOR tier IN SELECT * FROM jsonb_to_recordset(check_debit_config->'tiers') AS x("from" int, "to" int, fee numeric) LOOP
                IF debit_check_count >= tier."from" THEN
                    checks_in_tier := LEAST(debit_check_count, tier."to") - tier."from" + 1;
                    IF checks_in_tier > 0 THEN
                        tier_fee := checks_in_tier * tier.fee;
                        regular_fee := regular_fee + tier_fee;
                        regular_memo := array_append(regular_memo, 'Outgoing Check Fee: ' || checks_in_tier || ' check(s) at $' || tier.fee);
                    END IF;
                END IF;
            END LOOP;
        END IF;
        
        credit_check_config := fee_settings->'check_credit_missing_account_number';
        credit_check_count := (SELECT COUNT(*) FROM jsonb_to_recordset(p_credit_checks) AS x(amount numeric, has_account_number boolean) WHERE x.amount > 0 AND x.has_account_number = false);
        IF (credit_check_config->>'enabled')::boolean AND credit_check_count > 0 THEN
           cycle_start_date := CASE
                WHEN credit_check_config->>'cycle' = 'daily' THEN date_trunc('day', now())
                WHEN credit_check_config->>'cycle' = 'weekly' THEN date_trunc('week', now())
                WHEN credit_check_config->>'cycle' = 'monthly' THEN date_trunc('month', now())
                ELSE '1970-01-01'::date
            END;
           FOR tier IN SELECT * FROM jsonb_to_recordset(credit_check_config->'tiers') AS x("from" int, "to" int, fee numeric) LOOP
             IF credit_check_count >= tier."from" THEN
                checks_in_tier := LEAST(credit_check_count, tier."to") - tier."from" + 1;
                IF checks_in_tier > 0 THEN
                    tier_fee := checks_in_tier * tier.fee;
                    regular_fee := regular_fee + tier_fee;
                    regular_memo := array_append(regular_memo, 'Missing Acct # Fee: ' || checks_in_tier || ' check(s) at $' || tier.fee);
                END IF;
             END IF;
           END LOOP;
        END IF;
        
        rush_config := fee_settings->'rush_fee';
        rush_checks_count := (SELECT COUNT(*) FROM jsonb_to_recordset(p_debit_checks) AS x("isRush" boolean, amount numeric) WHERE x."isRush" AND x.amount > 0);
        IF rush_checks_count > 0 THEN is_check_rush := true; END IF;
        total_rush_check_amount := (SELECT COALESCE(SUM((c.value->>'amount')::numeric),0) FROM jsonb_array_elements(p_debit_checks) c WHERE (c.value->>'isRush')::boolean);

        IF (rush_config->>'enabled')::boolean AND (is_cash_rush OR is_check_rush) THEN
            IF is_cash_rush THEN
               FOR tier IN SELECT * FROM jsonb_to_recordset(rush_config->'cash'->'tiers') AS x("from" numeric, "to" numeric, fee numeric, fee_type text) LOOP
                   IF total_rush_cash_debit >= tier."from" AND (tier."to" IS NULL OR total_rush_cash_debit <= tier."to") THEN
                       IF tier.fee_type = 'flat' THEN rush_fee := rush_fee + tier.fee;
                       ELSE rush_fee := rush_fee + (total_rush_cash_debit * tier.fee / 100.0); END IF;
                       rush_memo := array_append(rush_memo, 'Rush Cash Fee');
                       EXIT;
                   END IF;
               END LOOP;
            END IF;
            
            IF is_check_rush THEN
               FOR tier IN SELECT * FROM jsonb_to_recordset(rush_config->'check'->'tiers') AS x("from" int, "to" int, fee numeric, fee_type text) LOOP
                    IF rush_checks_count >= tier."from" AND (tier."to" IS NULL OR rush_checks_count <= tier."to") THEN
                        IF tier.fee_type = 'flat' THEN rush_fee := rush_fee + (tier.fee * rush_checks_count);
                        ELSE rush_fee := rush_fee + (total_rush_check_amount * tier.fee / 100.0); END IF;
                        rush_memo := array_append(rush_memo, 'Rush Check Fee');
                        EXIT;
                    END IF;
                END LOOP;
            END IF;
        END IF;

        IF (is_cash_rush OR is_check_rush) AND (rush_config->'overwrite')::boolean THEN
            total_fee := rush_fee;
            fee_memo := array_to_string(rush_memo, ', ');
        ELSE
            total_fee := regular_fee + rush_fee;
            fee_memo := array_to_string(array_cat(regular_memo, rush_memo), ', ');
        END IF;

        RETURN QUERY SELECT total_fee, fee_memo;
    END;
    $_$;


