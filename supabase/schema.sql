CREATE FUNCTION public.generate_next_customer_id() RETURNS text
    LANGUAGE plpgsql SECURITY DEFINER
    AS $_$
DECLARE
    last_main_account_numeric integer;
    new_main_account_id text;
BEGIN
    -- Find the highest numeric account number among main accounts (those without a parent)
    SELECT COALESCE(MAX(CAST(REGEXP_REPLACE(account_number, '[^0-9]', '', 'g') AS integer)), 100)
    INTO last_main_account_numeric
    FROM customers
    WHERE parent_account_id IS NULL AND account_number ~ '^[0-9]+$';

    -- Increment to get the new main account number
    new_main_account_id := (last_main_account_numeric + 1)::text;

    RETURN new_main_account_id;
END;
$_$;


--
-- Name: generate_next_sub_account_id(text); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.generate_next_sub_account_id(parent_id text) RETURNS text
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
DECLARE
    last_sub_account_char char;
    new_sub_account_id text;
BEGIN
    -- Find the highest character suffix for the given parent
    SELECT MAX(RIGHT(account_number, 1))
    INTO last_sub_account_char
    FROM customers
    WHERE parent_account_id = parent_id;

    IF last_sub_account_char IS NULL THEN
        -- This is the first sub-account
        new_sub_account_id := parent_id || 'A';
    ELSE
        -- Increment the character
        new_sub_account_id := parent_id || CHR(ASCII(last_sub_account_char) + 1);
    END IF;

    RETURN new_sub_account_id;
END;
$$;


